def evidence_level(row):
    priority = int(row["priority"])
    cf = abs(Decimal(row["cf"]))
    if priority >= 9 or cf >= Decimal("0.700"):
        return "high"
    if priority >= 7 or cf >= Decimal("0.550"):
        return "medium"
    return "low"


