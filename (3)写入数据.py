def read_rule_records():
    base_records = list(csv.DictReader(StringIO(RULE_DATA.strip()), delimiter="|"))
    if len(base_records) != 100:
        raise ValueError(f"知识库基础种子数据必须是 100 条，当前为 {len(base_records)} 条")

    records = base_records + build_expanded_rule_records(base_records)
    ids = [row["id"] for row in records]
    if len(ids) != len(set(ids)):
        raise ValueError("知识库种子数据存在重复 ID")

    rule_names = [row["rule_name"] for row in records]
    if len(rule_names) != len(set(rule_names)):
        raise ValueError("知识库规则名称存在重复")

    domain_tags = [row["domain_tag"] for row in records]
    if len(domain_tags) != len(set(domain_tags)):
        raise ValueError("知识库 DomainTag 存在重复")

    for row in records:
        options_json = row.get("options_json") or ""
        if options_json:
            json.loads(options_json)

    return records


